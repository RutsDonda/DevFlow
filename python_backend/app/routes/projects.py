"""
app/routes/projects.py – Projects generated by the Architect agent.

  GET    /api/projects                 – list
  GET    /api/projects/{id}            – detail with all files
  GET    /api/projects/{id}/download   – ZIP archive
  DELETE /api/projects/{id}
"""

from fastapi import APIRouter, Depends, HTTPException, Response, status

from app.core.firebase import FirebaseUser
from app.core.security import get_registered_user
from app.models.schemas import ProjectDetail, ProjectSummary
from app.services import projects as project_service

router = APIRouter(prefix="/projects", tags=["projects"])


async def _owned(user: FirebaseUser, project_id: str) -> dict:
    project = await project_service.get_project(user.uid, project_id)
    if not project:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Project not found")
    return project


@router.get("", response_model=list[ProjectSummary])
async def list_projects(user: FirebaseUser = Depends(get_registered_user)):
    return await project_service.list_projects(user.uid)


@router.get("/{project_id}", response_model=ProjectDetail)
async def get_project(project_id: str, user: FirebaseUser = Depends(get_registered_user)):
    return project_service.serialize_project(await _owned(user, project_id), include_files=True)


@router.get("/{project_id}/download")
async def download_project(project_id: str, user: FirebaseUser = Depends(get_registered_user)):
    data, filename = project_service.build_zip(await _owned(user, project_id))
    return Response(
        content=data,
        media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


@router.delete("/{project_id}", status_code=204)
async def delete_project(project_id: str, user: FirebaseUser = Depends(get_registered_user)):
    if not await project_service.delete_project(user.uid, project_id):
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Project not found")
